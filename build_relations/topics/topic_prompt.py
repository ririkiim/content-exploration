EXCLUDED_KEYWORDS = {
    "해외영화제수상작",
    "황금종려상",
    "아카데미상",
}


def clean_keywords(keywords):
    result = []
    seen = set()

    if not isinstance(keywords, list):
        return result

    for item in keywords:
        if isinstance(item, dict):
            name = item.get("name", "")
        elif isinstance(item, str):
            name = item
        else:
            continue

        if not isinstance(name, str):
            continue

        name = " ".join(name.split())

        if not name:
            continue

        if name in EXCLUDED_KEYWORDS:
            continue

        key = name.casefold()

        if key in seen:
            continue

        seen.add(key)
        result.append(name)

    return result


def clean_genres(genres):
    result = []

    if not isinstance(genres, list):
        return result

    for item in genres:
        if isinstance(item, dict):
            name = item.get("name")
        else:
            name = item

        if isinstance(name, str):
            name = name.strip()

            if name and name not in result:
                result.append(name)

    return result


def prepare_content(content):
    """
    평가와 적재에서 동일하게 사용하는 입력.

    이전 평가 입력과 맞추기 위해
    original_title은 LLM 입력에서 제외한다.
    """

    return {
        "content_id": content["content_id"],
        "content_type": content["content_type"],
        "title": content["title"],
        "release_year": content.get("release_year"),
        "description": content.get("description") or "",
        "genres": clean_genres(content.get("genres")),
        "keywords": clean_keywords(content.get("keywords")),
    }


def build_input(content):
    return prepare_content(content)


def build_prompt(content):
    return (
        "다음 콘텐츠의 핵심 토픽을 추출해줘.\n\n"
        "입력 데이터:\n"
        + json.dumps(
            build_input(content),
            ensure_ascii=False,
            indent=2,
            default=str,
        )
    )